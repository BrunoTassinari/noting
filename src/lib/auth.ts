import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { nextCookies } from "better-auth/next-js";
import { db } from "@/db";
import * as schema from "@/db/schema";

// BETTER_AUTH_SECRET e BETTER_AUTH_URL são lidas do ambiente pelo Better Auth.
export const auth = betterAuth({
  database: drizzleAdapter(db, {
    provider: "pg",
    schema: {
      user: schema.user,
      session: schema.session,
      account: schema.account,
      verification: schema.verification,
    },
  }),
  emailAndPassword: {
    enabled: true,
    // Uso pessoal: sem cadastro público. Crie usuários com `npm run create-user`.
    disableSignUp: true,
  },
  session: {
    expiresIn: 60 * 60 * 24 * 30, // 30 dias
    updateAge: 60 * 60 * 24, // renova uma vez por dia
  },
  // Deve ser o último plugin: grava cookies a partir de Server Actions.
  plugins: [nextCookies()],
});
